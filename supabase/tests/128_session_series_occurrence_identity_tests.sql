-- Regression tests for Stage 1 of the recurring-session occurrence-identity redesign
-- (20261001150000_session_series_occurrence_identity_stage1.sql).
--
-- Covers the two real production incidents (2026-10-04 coach change Lotem->Shira,
-- 2026-10-06 time change 18:00->19:00) via structurally equivalent synthetic fixtures, plus
-- multi-candidate ownership, idempotency, and physical-slot-conflict handling. All fixtures
-- use far-future dates and real existing coach/profile ids to avoid colliding with seeded or
-- production-like data in this test database.
--
-- Each test was independently verified (same structure) against live production in a
-- rolled-back transaction before this migration was applied; see the engagement's forensic
-- and design-review record for the full derivation.
set client_min_messages to notice;

-- TEST 1: coach change -- edited occurrence remains, original coach is never regenerated by a
-- colliding sibling series, ownership stays with the edited series.
do $$
declare
  v_coach1 uuid; v_coach2 uuid; v_manager uuid;
  v_series_a uuid; v_series_b uuid; v_sess_a uuid; v_res json; v_claim_result text; v_count int;
begin
  select v into v_coach1 from _test_ids where k='coach';
  select v into v_manager from _test_ids where k='manager';
  v_coach2 := v_manager; -- a distinct real profile usable as an alternate coach_id

  perform set_config('app.current_uid', v_manager::text, true);

  insert into session_series (coach_id, anchor_date, start_time, max_participants, repeat_mode, status)
  values (v_coach1, current_date + 801, '18:00', 6, 'ongoing', 'active') returning id into v_series_a;
  insert into session_series (coach_id, anchor_date, start_time, max_participants, repeat_mode, status)
  values (v_coach1, current_date + 808, '18:00', 6, 'ongoing', 'active') returning id into v_series_b;

  perform _generate_series_occurrence_claim(v_series_a, current_date + 801);
  select id into v_sess_a from training_sessions where series_id = v_series_a and session_date = current_date + 801;
  if v_sess_a is null then raise exception 'TEST1 SETUP FAILED: series A occurrence not created'; end if;

  select staff_update_session_series_scope(v_sess_a, 'this', current_date+801, '18:00', v_coach2, 6, 60, false, false, false, null) into v_res;
  if not (v_res->>'ok')::boolean then raise exception 'TEST1 FAILED: edit rejected: %', v_res; end if;

  v_claim_result := _generate_series_occurrence_claim(v_series_b, current_date + 801);
  if v_claim_result <> 'series_logical_conflict' then
    raise exception 'TEST1 FAILED: expected series_logical_conflict, got %', v_claim_result;
  end if;

  if not exists (select 1 from training_sessions where id = v_sess_a and coach_id = v_coach2) then
    raise exception 'TEST1 FAILED: edited session missing or reverted';
  end if;
  if exists (select 1 from training_sessions where session_date = current_date+801 and start_time='18:00' and coach_id = v_coach1) then
    raise exception 'TEST1 FAILED: original-coach ghost was created -- this is the 2026-10-04 incident recurring';
  end if;
  select count(*) into v_count from training_sessions
  where session_date = current_date+801 and start_time='18:00' and coach_id in (v_coach1, v_coach2);
  if v_count <> 1 then raise exception 'TEST1 FAILED: expected exactly 1 session, found %', v_count; end if;

  raise notice 'TEST1 PASSED: coach-change regression (Lotem->Shira structure) blocked correctly';
end $$;

