-- TEST 8: forward-only self-protection -- delete, same legacy starting condition. The tombstone
-- must be established atomically by the delete itself, blocking both regeneration by this
-- series and reclaiming by a sibling series.
do $$
declare
  v_coach1 uuid; v_manager uuid;
  v_series_a uuid; v_series_b uuid; v_sess_a uuid; v_res json; v_claim_result text;
  v_target date := current_date + 806;
begin
  select v into v_coach1 from _test_ids where k='coach';
  select v into v_manager from _test_ids where k='manager';
  perform set_config('app.current_uid', v_manager::text, true);

  insert into session_series (coach_id, anchor_date, start_time, max_participants, repeat_mode, status)
  values (v_coach1, v_target, '18:00', 6, 'ongoing', 'active') returning id into v_series_a;
  insert into session_series (coach_id, anchor_date, start_time, max_participants, repeat_mode, status)
  values (v_coach1, v_target - 7, '18:00', 6, 'ongoing', 'active') returning id into v_series_b;

  insert into training_sessions (session_date, start_time, coach_id, max_participants, series_id, series_detached)
  values (v_target, '18:00', v_coach1, 6, v_series_a, false) returning id into v_sess_a;

  select staff_delete_session_series_scope(v_sess_a, 'this') into v_res;
  if not (v_res->>'ok')::boolean then raise exception 'TEST8 FAILED: delete rejected: %', v_res; end if;

  if exists (select 1 from training_sessions where id = v_sess_a) then
    raise exception 'TEST8 FAILED: session not actually deleted';
  end if;

  if not exists (
    select 1 from session_series_occurrences
    where series_id = v_series_a and template_occurrence_date = v_target and state = 'deleted'
  ) then
    raise exception 'TEST8 FAILED: delete did not establish a tombstone ledger row for a previously-unlinked legacy session';
  end if;

  v_claim_result := _generate_series_occurrence_claim(v_series_a, v_target);
  if v_claim_result <> 'already_handled' then
    raise exception 'TEST8 FAILED: deleted series own re-claim should be already_handled, got %', v_claim_result;
  end if;

  v_claim_result := _generate_series_occurrence_claim(v_series_b, v_target);
  if v_claim_result <> 'series_logical_conflict' then
    raise exception 'TEST8 FAILED: expected sibling series_logical_conflict after delete, got %', v_claim_result;
  end if;

  if exists (select 1 from training_sessions where session_date = v_target and start_time='18:00' and coach_id = v_coach1) then
    raise exception 'TEST8 FAILED: deleted occurrence ghost was regenerated by a sibling series';
  end if;

  raise notice 'TEST8 PASSED: delete from a legacy (no prior ledger row) session self-protects correctly, sibling blocked';
end $$;

-- TEST 9: existing-state-preservation -- this migration must never write to an existing
-- training_sessions row, even the known Shira/Lotem duplicate pair. There is deliberately no
-- backfill; series_occurrence_id stays null on every pre-existing row forever, unless and until
-- a future edit or delete touches that specific row.
do $$
declare
  v_series_x uuid; v_series_y uuid; v_sess_x uuid; v_sess_y uuid;
  v_coach1 uuid; v_target date := current_date + 807;
begin
  select v into v_coach1 from _test_ids where k='coach';

  insert into session_series (coach_id, anchor_date, start_time, max_participants, repeat_mode, status)
  values (v_coach1, v_target, '20:00', 6, 'ongoing', 'active') returning id into v_series_x;
  insert into session_series (coach_id, anchor_date, start_time, max_participants, repeat_mode, status)
  values (v_coach1, v_target - 7, '20:00', 6, 'ongoing', 'active') returning id into v_series_y;

  -- Two legacy, never-backfilled, colliding rows -- structurally identical to the real
  -- Shira/Lotem duplicate: two physical sessions, two series, same template slot+date, neither
  -- linked to a ledger row.
  insert into training_sessions (session_date, start_time, coach_id, max_participants, series_id, series_detached)
  values (v_target, '20:00', v_coach1, 6, v_series_x, true) returning id into v_sess_x;
  insert into training_sessions (session_date, start_time, coach_id, max_participants, series_id, series_detached)
  values (v_target + 1, '20:00', v_coach1, 6, v_series_y, true) returning id into v_sess_y;

  perform _maintain_session_series_horizon_core();
  perform _maintain_session_series_horizon_core();

  if (select series_occurrence_id from training_sessions where id = v_sess_x) is not null
     or (select series_occurrence_id from training_sessions where id = v_sess_y) is not null then
    raise exception 'TEST9 FAILED: a pre-existing, never-edited legacy row was linked to the ledger';
  end if;
  if not exists (select 1 from training_sessions where id = v_sess_x and session_date = v_target and start_time = '20:00' and coach_id = v_coach1) then
    raise exception 'TEST9 FAILED: pre-existing legacy row x was modified';
  end if;
  if not exists (select 1 from training_sessions where id = v_sess_y and session_date = v_target + 1 and start_time = '20:00' and coach_id = v_coach1) then
    raise exception 'TEST9 FAILED: pre-existing legacy row y was modified';
  end if;

  raise notice 'TEST9 PASSED: pre-existing legacy rows, including a Shira/Lotem-shaped duplicate, are never touched or linked by horizon maintenance';
end $$;

